def save_sheet_slices(b64_png, pack):
    """Разрезать лист 2×2 на четыре карточки 820×1230."""
    from PIL import Image
    im = Image.open(io.BytesIO(base64.b64decode(b64_png))).convert("RGB")
    w, h = im.size
    outs = []
    for i, cid in enumerate(pack):
        q = im.crop(((i % 2) * w // 2, (i // 2) * h // 2,
                     (i % 2 + 1) * w // 2, (i // 2 + 1) * h // 2))
        q = q.resize((820, 1230), Image.LANCZOS)
        out = ROOT / "img" / "posters" / src_image(cid).name
        out.parent.mkdir(parents=True, exist_ok=True)
        q.save(out, "WEBP", quality=82, method=6)
        outs.append(out)
    return outs


