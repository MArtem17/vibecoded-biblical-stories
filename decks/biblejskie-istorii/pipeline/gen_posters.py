        "местах сцены; во врезки их НЕ выноси. Внизу лента с надписью "
        "«НАЙДИ НА КАРТИНКЕ: " + find + "», а под ней РЯД ИЗ ТРЁХ небольших "
        "плашек-фактов одинаковой ширины: в каждой маленькая пиктограмма, "
        "крупное значение и короткая подпись под ним — " + facts_text(facts) + ". "
