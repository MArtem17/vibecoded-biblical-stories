"""
Общие константы и помощники пайплайна.

Здесь живут «зафиксированные» куски промпта, которые приклеиваются к КАЖДОЙ
странице. Это и есть наши правила, выработанные руками:
  - STYLE_LOCK   — единый стиль иллюстрации (берётся со входного эталона)
  - TEXT_ZONE    — верх кадра пустой под текст (под САМЫЙ ДЛИННЫЙ язык)
  - PRESERVE     — что не менять в персонаже (анти-дрейф)
  - NO_CHARACTER — строка для страниц, где персонажа нет (эталон = только стиль)

book.json держит только СЦЕНУ и ТЕКСТ. Всё остальное добавляется отсюда,
чтобы правки стиля/верстки делались в одном месте, а не в 16 промптах.
"""

import os
import io
import json
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load_json(name):
    with open(ROOT / name, "r", encoding="utf-8") as f:
        return json.load(f)


CONFIG = load_json("config.json")
BOOK = load_json("book.json")


# --- Зафиксированные фрагменты промпта (РУССКИЙ, как в нашем стандарте) -------

STYLE_LOCK = (
    " Используй ТОТ ЖЕ стиль иллюстрации, что на входном изображении: "
    "детская книжная акварель, мягкие контуры, тёплая земляная палитра, "
    "дружелюбно и сказочно, пропорции для книжки-картинки."
)

# Верхняя зона обязана вмещать самый длинный язык (немецкий/русский длиннее
# английского). Поэтому правило жёсткое, а не «по возможности».
TEXT_ZONE = (
    " ВАЖНО для вёрстки: верхние 40% кадра — открытое спокойное светлое небо "
    "или простой фон без важных деталей (туда ляжет текст на разных языках, "
    "включая длинные). Всё главное действие держи в нижних двух третях кадра."
)

# Универсально, без привязки к конкретному костюму: идентичность персонажа
# держим по самому эталону (лицо/волосы/одежда/аксессуары/палитра берутся со
# входного изображения). Так один common.py работает для любой книги.
PRESERVE = (
    " Персонажа со входного изображения НЕ перерисовывай: сохрани то же лицо, "
    "ту же бороду и причёску, ту же одежду и аксессуары, те же пропорции и "
    "палитру, что на входном изображении. Можно менять только позу, ракурс и "
    "сцену вокруг."
)

NO_CHARACTER = " На этой странице человека со входного изображения НЕ изображай."

FORMAT = " Вертикальный кадр 2:3, полностраничный фон. Без текста на картинке, без водяных знаков, без рамок."


def build_page_prompt(page):
    """Собрать финальный промпт страницы из сцены + зафиксированных правил."""
    p = page["image_prompt"] + STYLE_LOCK + TEXT_ZONE + FORMAT
    p += PRESERVE if page["character_present"] else NO_CHARACTER
    return p


def build_anchor_prompt():
    """Промпт эталонного листа персонажа (генерим один раз, выбираем лучший)."""
    return (
        "Детская книжная иллюстрация. Эталонный лист главного персонажа.\n\n"
        "Персонаж: " + BOOK["anchor_description"] + "\n\n"
        "Стиль: детская акварель, мягкие контуры, тёплая земляная палитра, "
        "дружелюбно и сказочно, пропорции для книжки-картинки (чуть крупнее "
        "голова, живая мимика).\n\n"
        "Композиция: персонаж в полный рост по центру, виден целиком (включая "
        "ноги), лёгкая естественная поза. Простой однотонный светлый фон.\n\n"
        "Оригинальный персонаж, без отсылок к фильмам и мультфильмам. "
        "Без текста, без водяных знаков, без рамок. Вертикальный кадр 2:3."
    )


# --- IO помощники -------------------------------------------------------------

def save_webp_from_b64(b64_png, out_path, width=None, quality=None):
    """Сохранить ответ модели (base64) как WebP заданной ширины."""
    from PIL import Image
    width = width or CONFIG["image"]["web_width"]
    quality = quality or CONFIG["image"]["webp_quality"]
    im = Image.open(io.BytesIO(base64.b64decode(b64_png))).convert("RGB")
    w, h = im.size
    im = im.resize((width, round(h * width / w)), Image.LANCZOS)
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    im.save(out_path, "WEBP", quality=quality, method=6)
    return out_path


def file_to_b64(path):
    with open(path, "rb") as f:
        return base64.b64encode(f.read()).decode("ascii")


def page_image_path(n):
    return os.path.join(CONFIG["paths"]["images_dir"], f"page_{n:02d}.webp")


def page_audio_path(lang, n):
    return os.path.join(CONFIG["paths"]["audio_dir"], lang, f"{n:02d}.mp3")
