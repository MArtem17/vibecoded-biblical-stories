def build_prompt(scene_text, has_hero):
    p = scene_text + " " + STYLE
    p += PRESERVE if has_hero else NO_CHARACTER
    return p


def gen_one(nn, slug, hero, scene, attempts=3):
    out = ROOT / "img" / ("plots_%s_%s.webp" % (nn, slug))
    ref = anchor_path(hero or "noah")
    prompt = build_prompt(scene, hero is not None)
    best = None  # (score, b64) — меньше = лучше
    for att in range(1, attempts + 1):
        with open(ref, "rb") as f:
            res = oai.images.edit(model=IMG_MODEL, image=[f], prompt=prompt,
                                  size=IMG_SIZE, quality="high")
        b64 = res.data[0].b64_json
        save_webp_from_b64(b64, out)
        ok, (ml, dk, pp) = tone_ok(out)
        print("  plots_%s (%s, попытка %d): L=%.0f тени=%.1f%% бумага=%.0f%% → %s"
              % (nn, slug, att, ml, dk, pp, "OK" if ok else "ПЕРЕГЕН"))
        if ok:
            return True
        score = max(0, 150 - ml) + max(0, dk - 6) * 10 + max(0, 25 - pp)
        if best is None or score < best[0]:
            best = (score, b64)
    save_webp_from_b64(best[1], out)
    print("  plots_%s: тон не в коридоре после %d попыток — оставлена лучшая, "
          "проверить глазами" % (nn, attempts))
    return False


def main(only=None):
    only = set(only or [])
    todo = [s for s in SCENES if not only or s[0] in only]
    print("Генерю %d сцен (%s, %s)…" % (len(todo), IMG_MODEL, IMG_SIZE))
    fails = []
    for nn, slug, hero, scene in todo:
        out = ROOT / "img" / ("plots_%s_%s.webp" % (nn, slug))
        if not only and out.exists():
            print("  plots_%s — уже есть, пропуск" % nn)
            continue
        if not gen_one(nn, slug, hero, scene):
            fails.append(nn)
    print("Готово." + (" Вне коридора тона: " + ", ".join(fails) if fails else ""))


if __name__ == "__main__":
    main(sys.argv[1:] or None)
